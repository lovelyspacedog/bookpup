_NICK_POOL: list[str] | None = None
_NICK_RE = re.compile(r"^[A-Z][a-zA-Z]{2,28}$")


def nick_pool() -> list[str]:
    global _NICK_POOL
    if _NICK_POOL is None:
        pool = [f"{a}{s}" for a in ADJECTIVES for s in SPECIES]
        random.shuffle(pool)
        _NICK_POOL = pool
    return _NICK_POOL


def random_nick() -> str:
    """Pick a random AdjectiveSpecies nick (≤ 30 chars for IRC)."""
    pool = nick_pool()
    for _ in range(32):
        cand = random.choice(pool)
        if len(cand) <= 30 and _NICK_RE.match(cand):
            return cand
    return random.choice(ADJECTIVES) + random.choice(SPECIES)